"""Repeatable LedgerFlow target-repository demo using the existing HiveMind API.

The script creates only under ``.local/ledgerflow`` by default. It starts the
dependency-free HTTP API in memory, obtains a temporary project token, connects
the generated Git checkout with the existing ``hivemind
connect`` CLI, and then uses the existing bridge/API operations for the writer,
consumer, challenge, stale check, and provenance inspection.

No model calls are made. The target repository and token are generated runtime
artifacts, not fixtures committed to this repository.
"""

from __future__ import annotations

import argparse
from contextlib import contextmanager
import json
import os
from pathlib import Path
import shutil
import stat
import subprocess
import sys
import threading
from typing import Any, Iterator
from urllib.parse import quote

from .api import HiveMindHTTPServer, HiveMindRuntime
from .auth import Identity
from .bridge import LocalBridge, git


PROJECT_ROOT = Path(__file__).resolve().parent.parent
TEMPLATE_ROOT = PROJECT_ROOT / "demo" / "ledgerflow" / "template"
DEFAULT_OUTPUT_ROOT = PROJECT_ROOT / ".local" / "ledgerflow"
MARKER_NAME = ".generated-by-hivemind-ledgerflow"
POLICY_PATH = "docs/payment-policy.md"
IMPLEMENTATION_PATH = "src/ledgerflow/payments.py"
MEMORY_TITLE = "Payment retries require one idempotency key"
MEMORY_BODY = (
    "LedgerFlow must reuse the same idempotency key and request fingerprint "
    "when an authorization times out; a changed fingerprint is a conflict. "
    "Reconcile the gateway reference before retrying with new input."
)


class LedgerFlowDemoError(RuntimeError):
    """A setup or demo assertion failed."""


def _json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2)


def _relative(path: Path) -> str:
    try:
        return path.resolve().relative_to(PROJECT_ROOT).as_posix()
    except ValueError:
        return path.resolve().as_posix()


def _remove_generated_tree(path: Path) -> None:
    """Remove a generated checkout on both POSIX and read-only Windows files."""

    def make_writable_and_retry(function: Any, filename: str, _error: Any) -> None:
        os.chmod(filename, stat.S_IRUSR | stat.S_IWUSR)
        function(filename)

    shutil.rmtree(path, onerror=make_writable_and_retry)


def prepare_repository(output_root: Path = DEFAULT_OUTPUT_ROOT, *, reset: bool = False) -> Path:
    """Materialize a clean target checkout from the tracked template."""

    output_root = output_root.resolve()
    target = output_root / "repo"
    marker = output_root / MARKER_NAME
    if not TEMPLATE_ROOT.is_dir():
        raise LedgerFlowDemoError(f"LedgerFlow template is missing: {TEMPLATE_ROOT}")
    if reset and target.exists():
        if not marker.is_file():
            raise LedgerFlowDemoError(f"Refusing to remove an unmarked output directory: {output_root}")
        _remove_generated_tree(target)
    if target.exists():
        if not (target / ".git").is_dir():
            raise LedgerFlowDemoError(f"Output exists but is not a Git repository: {target}")
        return target

    output_root.mkdir(parents=True, exist_ok=True)
    shutil.copytree(TEMPLATE_ROOT, target)
    git(target, "init", "-b", "main")
    git(target, "config", "user.email", "ledgerflow-demo@example.test")
    git(target, "config", "user.name", "LedgerFlow Demo")
    git(target, "add", ".")
    git(target, "commit", "-m", "Initial LedgerFlow payment target")
    marker.write_text(
        "Generated by python -m hivemind.ledgerflow_demo; safe to remove with --reset.\n",
        encoding="utf-8",
    )
    return target


@contextmanager
def _api_session() -> Iterator[tuple[HiveMindRuntime, str, str, str]]:
    """Yield a local API runtime, URL, project ID, and ephemeral agent token."""

    runtime = HiveMindRuntime(
        environ={
            "HIVEMIND_BACKEND": "memory",
            "HIVEMIND_USERS": "operator=operator",
        }
    )
    logged_in = runtime.auth.login("operator", "operator")
    if logged_in is None:
        raise LedgerFlowDemoError("Could not create the local demo operator identity")
    owner: Identity = logged_in[1]
    project_result = runtime.projects.create_project(
        owner,
        "LedgerFlow payment processing",
        "Synthetic payment target for the HiveMind provenance demo.",
    )
    if not project_result.get("ok"):
        raise LedgerFlowDemoError(f"Could not create the local demo project: {project_result}")
    project_id = project_result["project"]["id"]
    token, _ = runtime.auth.create_agent_token(owner, "LedgerFlow demo agent", project_id)
    server = HiveMindHTTPServer(("127.0.0.1", 0), runtime=runtime)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        yield runtime, f"http://127.0.0.1:{server.server_port}", project_id, token
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=3)


def _connect_with_cli(target: Path, url: str, project_id: str, token: str) -> None:
    """Use the shipped CLI to create the target's ignored bridge state."""

    environment = os.environ.copy()
    environment["HIVEMIND_AGENT_TOKEN"] = token
    environment["PYTHONPATH"] = os.pathsep.join(
        item for item in (str(PROJECT_ROOT), environment.get("PYTHONPATH", "")) if item
    )
    command = [
        sys.executable,
        "-m",
        "hivemind",
        "connect",
        "--repo",
        ".",
        "--url",
        url,
        "--project",
        project_id,
        "--remote",
        "ledgerflow.example.test/payment-processing",
        "--client",
        "opencode",
    ]
    completed = subprocess.run(
        command,
        cwd=target,
        env=environment,
        capture_output=True,
        text=True,
        timeout=30,
    )
    if completed.returncode != 0:
        detail = completed.stderr.strip() or completed.stdout.strip() or "no CLI error output"
        raise LedgerFlowDemoError(f"hivemind connect failed: {detail[-500:]}")


def _require_ok(label: str, result: Any) -> dict[str, Any]:
    if not isinstance(result, dict) or result.get("ok") is not True:
        raise LedgerFlowDemoError(f"{label} failed: {_json(result)}")
    return result


def _find_finding(recall: dict[str, Any], memory_id: str) -> dict[str, Any]:
    matches = [item for item in recall.get("findings", []) if item.get("id") == memory_id]
    if not matches:
        raise LedgerFlowDemoError(f"Finding {memory_id} was not returned by recall")
    return matches[0]


def _challenge_source(target: Path) -> str:
    """Change one bound policy source so the old finding must be rechecked."""

    policy = target / POLICY_PATH
    original = policy.read_text(encoding="utf-8")
    old = "Retries must\nreuse the same idempotency key and the same request fingerprint."
    new = (
        "Retries must reuse the same idempotency key and the same request fingerprint "
        "within the gateway's active idempotency window. Gateway v2 may rotate that "
        "window after reconciliation, so the retry contract needs review."
    )
    if old not in original:
        raise LedgerFlowDemoError("LedgerFlow policy no longer contains its challenge anchor")
    policy.write_text(original.replace(old, new, 1), encoding="utf-8")
    git(target, "add", POLICY_PATH)
    git(target, "commit", "-m", "Challenge retry policy assumptions")
    return git(target, "rev-parse", "HEAD")


def run_demo(output_root: Path = DEFAULT_OUTPUT_ROOT) -> dict[str, Any]:
    """Run writer, cold consumer, source challenge, stale recall, and explain."""

    target = prepare_repository(output_root, reset=True)
    with _api_session() as (_, url, project_id, token):
        _connect_with_cli(target, url, project_id, token)
        writer = LocalBridge(target, session="ledgerflow-writer")
        written = _require_ok(
            "writer finding",
            writer.call(
                "finding",
                {
                    "title": MEMORY_TITLE,
                    "body": MEMORY_BODY,
                    "paths": [POLICY_PATH, IMPLEMENTATION_PATH],
                    "classification": "observation",
                    "conflict_key": "ledgerflow:retry-idempotency",
                    "event_id": "ledgerflow-writer-v1",
                },
            ),
        )
        memory = written["memory"]
        memory_id = memory["id"]

        consumer = LocalBridge(target, session="ledgerflow-consumer")
        consumed = _require_ok("cold consumer recall", consumer.call("recall", {"query": "retry idempotency"}))
        consumer_finding = _find_finding(consumed, memory_id)

        challenge_head = _challenge_source(target)
        stale_consumer = LocalBridge(target, session="ledgerflow-stale-consumer")
        stale = _require_ok("stale consumer recall", stale_consumer.call("recall", {"query": "retry idempotency"}))
        stale_finding = _find_finding(stale, memory_id)
        explanation = _require_ok("provenance explanation", stale_consumer.call("explain", {"memory_id": memory_id}))
        overview = _require_ok(
            "graph overview",
            stale_consumer.request(
                "overview?repo_id=" + quote(stale_consumer.config["repo_id"], safe=""),
                get=True,
            ),
        )

        source_bindings = [
            {
                "path": source.get("path", source.get("data", {}).get("path")),
                "sha256": source.get("sha256", source.get("data", {}).get("sha256")),
            }
            for source in explanation.get("sources", [])
        ]
        assertions = {
            "writer_saved_source_bound_finding": memory.get("data", {}).get("paths")
            == [POLICY_PATH, IMPLEMENTATION_PATH],
            "cold_consumer_recalled_current_finding": consumer_finding.get("applicability") == "applicable",
            "challenge_created_new_git_head": challenge_head != memory.get("head"),
            "stale_consumer_flagged_changed_source": stale_finding.get("applicability") == "historical_source_changed",
            "provenance_names_policy_source": POLICY_PATH in {item.get("path") for item in source_bindings},
            "provenance_names_implementation_source": IMPLEMENTATION_PATH in {item.get("path") for item in source_bindings},
            "provenance_keeps_branch_binding": bool(explanation.get("branch_path")),
            "token_not_in_demo_result": True,
            "target_checkout_is_clean": not bool(git(target, "status", "--porcelain")),
        }
        result = {
            "ok": all(assertions.values()),
            "scenario": "ledgerflow-payment-retry",
            "synthetic": True,
            "target_repo": _relative(target),
            "writer": {
                "fresh_session": True,
                "memory_id": memory_id,
                "source_paths": memory.get("data", {}).get("paths", []),
                "source_head": memory.get("head"),
            },
            "consumer": {
                "fresh_session": True,
                "memory_id": memory_id,
                "applicability": consumer_finding.get("applicability"),
                "collection": consumer_finding.get("collection"),
            },
            "challenge": {
                "changed_path": POLICY_PATH,
                "head": challenge_head,
                "old_source_head": memory.get("head"),
            },
            "stale": {
                "memory_id": memory_id,
                "applicability": stale_finding.get("applicability"),
                "exclusions": [item for item in stale.get("exclusions", []) if item.get("id") == memory_id],
            },
            "provenance": {
                "memory_id": memory_id,
                "source_bindings": source_bindings,
                "branch_path": explanation.get("branch_path", []),
                "inheritance_path": explanation.get("inheritance_path"),
                "provenance_notice": explanation.get("provenance_notice"),
                "graph_overview": {
                    "repository_count": len(overview.get("repository", [])),
                    "branch_count": len(overview.get("branch", [])),
                    "observation_count": len(overview.get("observation", [])),
                    "completeness": overview.get("completeness", {}),
                },
            },
            "assertions": assertions,
        }
        serialized = _json(result)
        if token in serialized:
            result["assertions"]["token_not_in_demo_result"] = False
            result["ok"] = False
        return result


def _print_result(result: dict[str, Any]) -> int:
    print(_json(result))
    return 0 if result.get("ok") else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)
    for command in ("demo", "inspect", "smoke"):
        command_parser = subparsers.add_parser(command, help={"demo": "run all four LedgerFlow stages", "inspect": "run and print provenance", "smoke": "run assertions and print a compact result"}[command])
        command_parser.add_argument("--output-root", type=Path, default=DEFAULT_OUTPUT_ROOT, help="generated output directory (default: .local/ledgerflow)")
    prepare_parser = subparsers.add_parser("prepare", help="materialize the ignored target repository")
    prepare_parser.add_argument("--reset", action="store_true", help="replace the marked generated checkout")
    prepare_parser.add_argument("--output-root", type=Path, default=DEFAULT_OUTPUT_ROOT, help="generated output directory (default: .local/ledgerflow)")
    args = parser.parse_args(argv)
    try:
        if args.command == "prepare":
            target = prepare_repository(args.output_root, reset=args.reset)
            return _print_result({"ok": True, "target_repo": _relative(target), "reset": args.reset})
        result = run_demo(args.output_root)
        if args.command == "inspect":
            result = {"ok": result["ok"], "scenario": result["scenario"], "stale": result["stale"], "provenance": result["provenance"], "assertions": result["assertions"]}
        elif args.command == "smoke":
            result = {"ok": result["ok"], "scenario": result["scenario"], "assertions": result["assertions"]}
        return _print_result(result)
    except (LedgerFlowDemoError, OSError, ValueError) as exc:
        return _print_result({"ok": False, "error": str(exc)})


if __name__ == "__main__":  # pragma: no cover - exercised by the CLI smoke test
    raise SystemExit(main())
